const sourceIcons: Record<string, LucideIcon> = {
  "Web": Globe,
  "Podcast": Mic,
  // Goodreads-imported books (#147) — the open-book glyph, matching the
  // feed↔books toolbar toggle, rather than the generic globe.
  "Goodreads": BookOpen,
}

interface SourceIconProps {
  platform: string
  className?: string
}

export function SourceIcon({ platform, className = "w-4 h-4" }: SourceIconProps) {
  // Custom brand icons
  switch (platform) {
    case "Spotify":
      return <SpotifyIcon className={className} />
    case "Audible":
      return <AudibleIcon className={className} />
    case "Substack":
      return <SubstackIcon className={className} />
    case "YouTube":
      return <YouTubeIcon className={className} />
    case "LessWrong":
      return (
        <Image
          src="/lesswrong-icon.ico"
          alt="LessWrong"
          width={16}
          height={16}
          className={className}
        />
      )
    default:
      const Icon = sourceIcons[platform] || Globe
      return <Icon className={className} />
  }
}

export function getSourceIcon(platform: string): LucideIcon {
  return sourceIcons[platform] || Globe
}
