-- Migration: Add rss_feeds table (dynamic RSS feed management, #149)
-- Description: Moves feed config out of lib/rss/config.ts into the DB.
--   Seeds the 10 existing feeds. Cron reads active rows; UI manages them.
-- Date: 2026-05-16

CREATE TABLE IF NOT EXISTS rss_feeds (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url                 TEXT NOT NULL UNIQUE,
  label               TEXT NOT NULL,
  author_name         TEXT,
  platform            TEXT NOT NULL,
  feed_type           TEXT NOT NULL CHECK (feed_type IN ('substack','lesswrong','generic')),
  active              BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_fetched_at     TIMESTAMPTZ,
  last_success_at     TIMESTAMPTZ,
  last_error          TEXT,
  last_error_at       TIMESTAMPTZ,
  last_item_count     INT,
  consecutive_errors  INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS rss_feeds_active_idx ON rss_feeds (active) WHERE active = TRUE;

-- Reuse the existing global trigger function (same one queue_items uses).
CREATE TRIGGER update_rss_feeds_updated_at
  BEFORE UPDATE ON rss_feeds
  FOR EACH ROW
  EXECUTE FUNCTION public.update_updated_at_column();

ALTER TABLE rss_feeds ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE rss_feeds IS 'RSS feeds polled by the rss-sync cron. Seeded from the former lib/rss/config.ts (#149).';

