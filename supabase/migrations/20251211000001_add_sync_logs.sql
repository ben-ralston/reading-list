-- Create sync_logs table for tracking sync operations
CREATE TABLE IF NOT EXISTS sync_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,  -- 'spotify', 'audible', 'substack', 'elevenreader'
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'running',  -- 'running', 'success', 'error'
  items_processed INT DEFAULT 0,
  items_created INT DEFAULT 0,
  items_updated INT DEFAULT 0,
  items_skipped INT DEFAULT 0,
  error_message TEXT,
  metadata JSONB  -- For any additional debug info
);

-- Add check constraint for valid status values
ALTER TABLE sync_logs
  ADD CONSTRAINT sync_logs_valid_status
  CHECK (status IN ('running', 'success', 'error'));

-- Add check constraint for valid source values
ALTER TABLE sync_logs
  ADD CONSTRAINT sync_logs_valid_source
  CHECK (source IN ('spotify', 'audible', 'substack', 'elevenreader'));

-- Indexes for common queries
CREATE INDEX IF NOT EXISTS idx_sync_logs_source ON sync_logs (source);
CREATE INDEX IF NOT EXISTS idx_sync_logs_started_at ON sync_logs (started_at DESC);
CREATE INDEX IF NOT EXISTS idx_sync_logs_status ON sync_logs (status);

-- Comments
COMMENT ON TABLE sync_logs IS
